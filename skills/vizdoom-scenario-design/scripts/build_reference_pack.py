def provenance(
    title: str, intro: list[str], sources: list[tuple[str, Path]], versions: list[str]
) -> list[str]:
    lines = [
        f"<!-- Generated by {GENERATOR}; do not edit by hand. -->",
        f"# {title}",
        "",
        *intro,
        "",
        "Provenance:",
        "",
    ]
    lines += [f"- {v}" for v in versions]
    lines += [
        f"- `{label}` (sha256 `{sha256_prefix(path)}`)" for label, path in sources
    ]
    return lines + [""]


def write(path: Path, lines: list[str]) -> None:
    path.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    print(f"Wrote {path}")


def build(root: Path, acc_dir: Path, out: Path) -> None:
    zspecial_path = acc_dir / "zspecial.acs"
    for required in (zspecial_path, root / ENGINE_SRC / "p_acs.cpp", DATA_TSV):
        if not required.is_file():
            sys.exit(f"Missing input: {required}")
    engine = load_engine(root)
    decls = parse_zspecial(zspecial_path)
    builtins, tsv_header = load_acc_builtins(DATA_TSV)
    versions = [f"Engine: {engine.version}", f"Compiler: {acc_version(acc_dir)}"]
    acc_label = "acc/zspecial.acs (ACC 1.60, shipped in COMRAD DoomGen/acc/)"
    tsv_label = f"scripts/data/acc_builtins.tsv ({tsv_header[1] if len(tsv_header) > 1 else 'rheit/acc 1.60'})"
    src_label = ENGINE_SRC

    supported_builtins, unsupported = [], []
    for b in sorted(builtins, key=lambda b: b.display.lower()):
        ok, reason = builtin_status(b, engine)
        args = "printf-like" if b.lo < 0 else arity(b.lo, b.hi)
        opcodes = ", ".join(f"{p} ({n})" for p, n in b.pcodes)
        if reason and ok:
            opcodes += f"; {reason}"
        if ok:
            supported_builtins.append(
                [f"`{b.display}`", args, "yes" if b.returns else "no", b.kind, opcodes]
            )
        else:
            unsupported.append([f"`{b.display}`", args, f"ACC {b.kind}", reason])

    supported_acsf = []
    seen_ids: set[int] = set()
    for d in sorted((d for d in decls if d.number < 0), key=lambda d: d.name.lower()):
        ok, note = acsf_status(d, engine)
        if ok:
            supported_acsf.append(
                [f"`{d.name}`", arity(d.lo, d.hi), str(-d.number), note or d.note]
            )
            seen_ids.add(-d.number)
        else:
            unsupported.append(
                [f"`{d.name}`", arity(d.lo, d.hi), f"ACC function {d.number}", note]
            )

    for d in sorted((d for d in decls if d.number >= 0), key=lambda d: d.number):
        ok, reason = special_status(d.number, engine)
        if not ok:
            note = f"{reason}; zspecial note: {d.note}" if d.note else reason
            unsupported.append(
                [f"`{d.name}`", arity(d.lo, d.hi), f"line special {d.number}", note]
            )

    engine_only = sorted(
        (
            name
            for num, name in engine.acsf_by_num.items()
            if num not in seen_ids and f"ACSF_{name}" in engine.acsf_cases
        ),
        key=str.lower,
    )

    sources_acs = [
        (acc_label, zspecial_path),
        (tsv_label, DATA_TSV),
        (f"{src_label}/p_acs.h", root / ENGINE_SRC / "p_acs.h"),
        (f"{src_label}/p_acs.cpp", root / ENGINE_SRC / "p_acs.cpp"),
    ]
    lines = provenance(
        "ACS functions supported by ViZDoom (ZDoom 2.8.1)",
        [
            "Every function below is both declared by the ACC 1.60 compiler and handled by the ViZDoom engine's",
            "ACS interpreter. Anything that is not listed here or in `line_specials.md` must be treated as",
            "unsupported, even if the ZDoom wiki documents it or `acc` compiles it (see `acs_unsupported.md`).",
            "ACS is case-insensitive; the CamelCase spelling is conventional. Arguments are `min-max`.",
            "Semantics of each function: see the ZDoom wiki page of the same name, but check",
            "`zdoom_wiki_index.md` first, because many pages describe later GZDoom behaviour.",
        ],
        sources_acs,
        versions,
    )
    lines += [
        f"## Core built-ins and statements ({len(supported_builtins)})",
        "",
        "Compiled to dedicated p-codes. A built-in with two p-codes has a constant-argument (direct) form.",
        "",
    ]
    lines += md_table(
        ["Name", "Args", "Returns", "Kind", "Engine p-code"], supported_builtins
    )
    lines += [
        "",
        f"## Extension functions ({len(supported_acsf)})",
        "",
        "Called through `PCD_CALLFUNC` with the id below (`ACSF_*` in `p_acs.cpp`).",
        "",
    ]
    lines += md_table(["Name", "Args", "Id", "Note"], supported_acsf)
    if engine_only:
        lines += [
            "",
            "## Implemented by the engine but not declared by ACC 1.60",
            "",
            "These cannot be called by name from ACC-compiled scripts: "
            + ", ".join(f"`{n}`" for n in engine_only)
            + ".",
        ]
    lines += [
        "",
        "## Line specials",
        "",
        "Line specials (`Door_Open`, `Floor_MoveToValue`, `Thing_Remove`, `Exit_Normal`, ...) can also be",
        "called like functions from ACS. The callable ones are listed in `line_specials.md`.",
    ]
    write(out / "acs_functions.md", lines)

    lines = provenance(
        "ACS functions that compile but do not work in ViZDoom",
        [
            "Do not use these. ACC 1.60 accepts them (they are declared for GZDoom, Zandronum, Skulltag,",
            "Eternity or ZDaemon), but the ViZDoom engine has no working handler, and `acc` gives no warning.",
            "The symptom depends on the kind (see the last column):",
            "",
            "- extension functions (`ACC function -N`) silently return 0 and do nothing;",
            "- p-code built-ins without a handler stop the whole script (`Unknown P-Code` on the console);",
            "- line specials mapped to `LS_NOP` or numbered above 255 do nothing.",
            "",
            "Example: `SetActivatorToPlayer` (Zandronum) silently does nothing; use `SetActivator(tid)`.",
        ],
        sources_acs
        + [
            (f"{src_label}/actionspecials.h", root / ENGINE_SRC / "actionspecials.h"),
            (f"{src_label}/p_lnspec.cpp", root / ENGINE_SRC / "p_lnspec.cpp"),
        ],
        versions,
    )
    lines += [f"## Unsupported ({len(unsupported)})", ""]
    lines += md_table(
        ["Name", "Args", "Declared as", "Why it does not work"], unsupported
    )
    write(out / "acs_unsupported.md", lines)

    declared = {d.number: d for d in decls if d.number >= 0}
    rows = []
    for num in sorted(set(engine.specials) | set(declared)):
        if num in engine.specials:
            name, lo, hi, line_args, note = engine.specials[num]
        else:
            name, lo, hi, line_args, note = (
                declared[num].name,
                -1,
                -1,
                -1,
                "not defined in actionspecials.h",
            )
        ok, reason = special_status(num, engine)
        script_args = "line only" if lo < 0 else arity(lo, hi)
        acc = "yes" if num in declared else "no"
        rows.append(
            [
                str(num),
                f"`{name}`",
                script_args,
                str(line_args) if line_args >= 0 else "-",
                "yes" if ok else "no",
                acc,
                reason or note,
            ]
        )
    lines = provenance(
        "Line specials in ViZDoom (ZDoom 2.8.1)",
        [
            "Line specials can be attached to linedefs and things in a map, or called from ACS like functions.",
            "`Works` means the engine maps the number to a real handler and scripts may call it;",
            "`no` means it is missing, line-only, or mapped to `LS_NOP`. `In ACC` means `zspecial.acs` declares it.",
            "Script args are the arguments accepted from ACS (`min-max`); line args are the map-editor arguments.",
        ],
        [
            (f"{src_label}/actionspecials.h", root / ENGINE_SRC / "actionspecials.h"),
            (f"{src_label}/p_lnspec.cpp", root / ENGINE_SRC / "p_lnspec.cpp"),
            (acc_label, zspecial_path),
        ],
        versions,
    )
    lines += md_table(
        ["#", "Name", "Script args", "Line args", "Works", "In ACC", "Note"], rows
    )
    write(out / "line_specials.md", lines)

    static = root / STATIC_DIR
    actors = parse_actors(static)
    ednums, spawnnums = parse_mapinfo_numbers(static, MAPINFO_ROOT)
    ed_by_class: dict[str, list[int]] = {}
    for num, cls in ednums.items():
        ed_by_class.setdefault(cls.lower(), []).append(num)
    sp_by_class: dict[str, list[int]] = {}
    for num, cls in spawnnums.items():
        sp_by_class.setdefault(cls.lower(), []).append(num)

    def nums(table: dict[str, list[int]], name: str) -> str:
        return ", ".join(str(n) for n in sorted(table.get(name.lower(), []))) or "-"

    doom_rows, base_rows, other_rows = [], [], []
    for a in sorted(actors, key=lambda a: a.name.lower()):
        row = [
            f"`{a.name}`",
            a.parent or "-",
            nums(ed_by_class, a.name),
            nums(sp_by_class, a.name),
        ]
        has_num = a.name.lower() in ed_by_class or a.name.lower() in sp_by_class
        if a.game in OTHER_GAMES and not has_num:
            other_rows.append([f"`{a.name}`", a.parent or "-", a.game])
        elif a.game == "doom" or has_num:
            doom_rows.append(row + [a.replaces or "-", a.path.removeprefix("actors/")])
        else:
            base_rows.append(
                row[:2] + ["yes" if a.native else "no", a.path.removeprefix("actors/")]
            )
    specials_rows = [
        [str(n), v]
        for n, v in sorted(ednums.items())
        if v.startswith("$") or v.lower() not in {a.name.lower() for a in actors}
    ]

    lines = provenance(
        "Actor classes in ViZDoom (ZDoom 2.8.1, Doom 2 / Freedoom)",
        [
            "Classes defined by the engine's built-in DECORATE (`vizdoom.pk3`). Use these names in",
            "`SpawnSpot`, `Thing_Spawn` (via SpawnNum), DECORATE `ACTOR Name : Parent`, and map things",
            "(via DoomEdNum). A parent class that is not in this file does not exist in this engine",
            "(e.g. `PowerupNone`), and the WAD will fail to load. Numbers come from the Doom 2 MAPINFO chain",
            f"(`{MAPINFO_ROOT}` and its includes), which is what `freedoom2.wad` uses.",
        ],
        [
            (f"{STATIC_DIR}/decorate.txt", static / "decorate.txt"),
            (f"{STATIC_DIR}/{MAPINFO_ROOT}", static / MAPINFO_ROOT),
            (f"{STATIC_DIR}/mapinfo/doomcommon.txt", static / "mapinfo/doomcommon.txt"),
            (f"{STATIC_DIR}/mapinfo/doomitems.txt", static / "mapinfo/doomitems.txt"),
            (f"{STATIC_DIR}/mapinfo/common.txt", static / "mapinfo/common.txt"),
        ],
        versions,
    )
    lines += [
        f"## Doom / Freedoom classes and classes with an editor or spawn number ({len(doom_rows)})",
        "",
    ]
    lines += md_table(
        ["Class", "Parent", "DoomEdNum", "SpawnNum", "Replaces", "File"], doom_rows
    )
    lines += [
        "",
        "## Special editor numbers",
        "",
        "Editor numbers that do not name an actor class directly.",
        "",
    ]
    lines += md_table(["DoomEdNum", "Meaning"], specials_rows)
    lines += [
        "",
        f"## Base, inventory and utility classes ({len(base_rows)})",
        "",
        "Shared parents (`Inventory`, `Health`, `Powerup`, `Weapon`, ...) and helpers. `native` classes have",
        "C++ behaviour and are typically used as parents.",
        "",
    ]
    lines += md_table(["Class", "Parent", "Native", "File"], base_rows)
    lines += [
        "",
        f"## Classes of other games ({len(other_rows)})",
        "",
        "Defined in `vizdoom.pk3`, but `freedoom2.wad` ships no sprites or sounds for them, so do not",
        "use them in Doom 2 / Freedoom scenarios.",
        "",
    ]
    lines += md_table(["Class", "Parent", "Game"], other_rows)
    write(out / "actor_classes.md", lines)


def find_vizdoom_root(start: Path) -> Path | None:
    for candidate in (start, *start.parents):
        if (candidate / ENGINE_SRC / "p_acs.cpp").is_file():
            return candidate
    return None


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--vizdoom-root",
        type=Path,
        help="ViZDoom source checkout (default: search upwards)",
    )
    parser.add_argument(
        "--acc-dir",
        type=Path,
        help="Directory with acc and zspecial.acs (default: $VIZDOOM_ACC_DIR or <root>/DoomGen/acc)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="Output directory (default: references/)",
    )
    parser.add_argument(
        "--acc-src",
        type=Path,
        help="rheit/acc checkout (tag 1.60): re-extract scripts/data/acc_builtins.tsv and exit",
    )
    args = parser.parse_args()

    if args.acc_src:
        vendor_acc_builtins(args.acc_src, DATA_TSV)
        return
    root = (
        args.vizdoom_root
        or find_vizdoom_root(Path.cwd())
        or find_vizdoom_root(SKILL_DIR)
    )
    if root is None:
        sys.exit("Cannot find a ViZDoom source checkout; pass --vizdoom-root.")
    root = root.resolve()
    acc_dir = args.acc_dir or (
        Path(os.environ["VIZDOOM_ACC_DIR"])
        if "VIZDOOM_ACC_DIR" in os.environ
        else root / "DoomGen" / "acc"
    )
    args.out.mkdir(parents=True, exist_ok=True)
    build(root, acc_dir, args.out)


if __name__ == "__main__":
    main()
