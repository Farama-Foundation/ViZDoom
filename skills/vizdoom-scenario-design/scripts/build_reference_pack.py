# --------------------------------------------------------------------------
# Generic helpers
# --------------------------------------------------------------------------


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def sha256_prefix(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def strip_c_comments(text: str) -> str:
    """Remove ``/* */`` and ``//`` comments (sources here have no ``//`` in strings)."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_c_enum(body: str) -> dict[str, int]:
    """Parse the body of a C enum (between braces) into name -> value."""
    values: dict[str, int] = {}
    current = -1
    for item in strip_c_comments(body).split(","):
        item = item.strip()
        if not item:
            continue
        match = re.fullmatch(r"(\w+)\s*(?:=\s*(-?\w+))?", item)
        if not match:
            raise ValueError(f"Cannot parse enum item: {item!r}")
        name, expr = match.groups()
        if expr is not None:
            current = (
                int(expr, 0) if expr[0].isdigit() or expr[0] == "-" else values[expr]
            )
        else:
            current += 1
        values[name] = current
    return values


def enum_body(text: str, anchor: str) -> str:
    """Return the text between the braces of the enum that contains ``anchor``."""
    pos = text.index(anchor)
    start = text.rindex("{", 0, pos)
    end = text.index("}", pos)
    return text[start + 1 : end]


def case_labels(text: str, prefix: str) -> set[str]:
    return set(re.findall(rf"\bcase\s+({prefix}\w+)\s*:", strip_c_comments(text)))


def stub_case_labels(text: str, prefix: str) -> set[str]:
    """Case labels whose body only reports that the feature is not supported."""
    stubs = set()
    for match in re.finditer(rf"\bcase\s+({prefix}\w+)\s*:", text):
        end = text.find("break;", match.end())
        if end != -1 and "doesn't support" in text[match.end() : end]:
            stubs.add(match.group(1))
    return stubs


def arity(lo: int, hi: int) -> str:
    return str(lo) if lo == hi else f"{lo}-{hi}"


def md_escape(text: str) -> str:
    return text.replace("|", "\\|").strip()


def md_table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(md_escape(c) for c in row) + " |" for row in rows]
    return lines


