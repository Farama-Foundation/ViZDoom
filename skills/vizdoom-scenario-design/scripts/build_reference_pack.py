@dataclass
class Engine:
    pcd_by_num: dict[int, str]
    pcd_cases: set[str]
    pcd_stubs: set[str]
    acsf_by_num: dict[int, str]
    acsf_cases: set[str]
    specials: dict[int, tuple[str, int, int, int, str]]
    ls_table: dict[int, str]
    version: str


def load_engine(root: Path) -> Engine:
    src = root / ENGINE_SRC
    p_acs_h = read_text(src / "p_acs.h")
    p_acs_cpp = read_text(src / "p_acs.cpp")
    pcd_values = parse_c_enum(enum_body(p_acs_h, "PCD_NOP,"))
    pcd_by_num = {v: k for k, v in pcd_values.items() if k != "PCODE_COMMAND_COUNT"}
    acsf_values = parse_c_enum(enum_body(p_acs_cpp, "ACSF_GetLineUDMFInt"))
    acsf_by_num = {v: k[len("ACSF_") :] for k, v in acsf_values.items()}

    specials = {}
    for line in read_text(src / "actionspecials.h").splitlines():
        match = re.match(
            r"\s*DEFINE_SPECIAL\(\s*(\w+)\s*,\s*(\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\)\s*(?://\s*(.*))?",
            line,
        )
        if match:
            name, num, lo, hi, line_args, note = match.groups()
            specials[int(num)] = (
                name,
                int(lo),
                int(hi),
                int(line_args),
                (note or "").strip(),
            )

    lnspec = read_text(src / "p_lnspec.cpp")
    table_start = lnspec.index("lnSpecFunc LineSpecials[")
    table = lnspec[table_start : lnspec.index("};", table_start)]
    ls_table = {
        int(n): f for n, f in re.findall(r"/\*\s*(\d+)\s*\*/\s*(LS_\w+)", table)
    }

    cmake = read_text(root / "CMakeLists.txt")
    vzd = re.search(r"project\(ViZDoom VERSION ([0-9.]+)\)", cmake)
    zdoom = re.search(
        r'#define\s+RC_PRODUCTVERSION2\s+"([^"]+)"', read_text(src / "version.h")
    )
    version = f"ViZDoom {vzd.group(1) if vzd else '?'} (ZDoom {zdoom.group(1) if zdoom else '?'} fork)"
    return Engine(
        pcd_by_num,
        case_labels(p_acs_cpp, "PCD_"),
        stub_case_labels(p_acs_cpp, "PCD_"),
        acsf_by_num,
        case_labels(p_acs_cpp, "ACSF_"),
        specials,
        ls_table,
        version,
    )


UNKNOWN_PCODE = "the script stops with 'Unknown P-Code'"


def builtin_status(builtin: AccBuiltin, engine: Engine) -> tuple[bool, str]:
    """A built-in works if the engine handles every p-code it compiles to (matched by number)."""
    count = max(engine.pcd_by_num) + 1
    notes = []
    for pcd, num in builtin.pcodes:
        engine_name = engine.pcd_by_num.get(num)
        if engine_name is None:
            return (
                False,
                f"p-code {num} ({pcd}) is newer than the engine's {count} p-codes; {UNKNOWN_PCODE}",
            )
        alias = "" if engine_name == pcd else f" (named {engine_name} in the engine)"
        if engine_name not in engine.pcd_cases:
            return (
                False,
                f"no engine handler for p-code {num} ({pcd}){alias}; {UNKNOWN_PCODE}",
            )
        if engine_name in engine.pcd_stubs:
            return (
                False,
                f"engine handler for {engine_name} only prints that it is not supported",
            )
        if alias:
            notes.append(f"{pcd} is {engine_name} in the engine")
    return True, "; ".join(notes)


def acsf_origin(number: int) -> str:
    for lo, hi, origin in ACSF_ORIGINS:
        if lo <= number <= hi:
            return origin
    return "unknown"


def acsf_status(decl: AccDecl, engine: Engine) -> tuple[bool, str]:
    func_id = -decl.number
    engine_name = engine.acsf_by_num.get(func_id)
    if engine_name is None:
        return (
            False,
            f"{acsf_origin(func_id)} function; id {func_id} is not in the engine, the call silently returns 0",
        )
    if f"ACSF_{engine_name}" not in engine.acsf_cases:
        return False, f"ACSF_{engine_name} has no interpreter case"
    if engine_name.lower() != decl.name.lower():
        return True, f"engine name: {engine_name}"
    return True, ""


def special_status(number: int, engine: Engine) -> tuple[bool, str]:
    if number not in engine.ls_table:
        return (
            False,
            f"number {number} has no slot in the engine's 256-entry LineSpecials table, does nothing",
        )
    if engine.ls_table[number] == "LS_NOP":
        return False, "maps to LS_NOP (defined so WADs load), does nothing"
    if number in engine.specials and engine.specials[number][1] < 0:
        return False, "line-only special (cannot be called from a script)"
    return True, ""


