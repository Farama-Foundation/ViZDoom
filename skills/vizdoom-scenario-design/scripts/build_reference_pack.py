#!/usr/bin/env python3
"""Generate the version-pinned ACS/actor reference pack of this skill.

ViZDoom runs a fork of ZDoom 2.8.1, while the online ZDoom wiki documents
modern GZDoom, and the ACC 1.60 compiler accepts functions this engine never
implements. This script derives the reference tables from the sources that
decide what actually works:

* ``zspecial.acs`` (ACC): every line special and extension function the
  compiler declares.
* ``scripts/data/acc_builtins.tsv``: the p-code built-ins and print-like
  statements hard-coded in ACC 1.60 (``symbol.c``/``token.c``), vendored from
  https://github.com/rheit/acc/tree/1.60 (regenerate with ``--acc-src``).
* ``src/vizdoom/src/p_acs.h`` and ``p_acs.cpp``: the p-codes and ``ACSF_*``
  functions the engine's interpreter handles.
* ``src/vizdoom/src/actionspecials.h`` and ``p_lnspec.cpp``: line specials
  and whether they map to a real handler or to ``LS_NOP``.
* ``src/vizdoom/wadsrc/static/decorate.txt`` (+ includes) and
  ``mapinfo/doom2.txt`` (+ includes): actor classes, parents, editor numbers.

The output is deterministic (no timestamps, sorted rows), so it can be
committed and re-generated byte for byte.

Usage (from a ViZDoom checkout):
    python skills/vizdoom-scenario-design/scripts/build_reference_pack.py \
        --vizdoom-root . --acc-dir DoomGen/acc
"""

