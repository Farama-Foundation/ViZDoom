@dataclass
class AccDecl:
    """A ``N:Name(min[,max])`` declaration from zspecial.acs."""

    number: int
    name: str
    lo: int
    hi: int
    note: str = ""


def parse_zspecial(path: Path) -> list[AccDecl]:
    decls = []
    pattern = re.compile(
        r"^\s*(-?\d+)\s*:\s*(\w+)\s*\(\s*(\d+)\s*(?:,\s*(\d+)\s*)?\)\s*,?\s*(?://\s*(.*))?$"
    )
    for line in read_text(path).splitlines():
        if line.lstrip().startswith("//"):
            continue
        match = pattern.match(line)
        if not match:
            continue
        number, name, lo, hi, note = match.groups()
        if name == "__EndOfList__":
            continue
        lo_i = int(lo)
        hi_i = int(hi) if hi is not None else lo_i
        decls.append(AccDecl(int(number), name, lo_i, hi_i, (note or "").strip()))
    return decls


@dataclass
class AccBuiltin:
    """A p-code built-in or print-like statement hard-coded in ACC."""

    name: str
    display: str
    kind: str
    lo: int
    hi: int
    returns: bool
    pcodes: list[tuple[str, int]] = field(default_factory=list)


TSV_COLUMNS = ["name", "display", "kind", "args_min", "args_max", "returns", "pcodes"]

# Print-like statements are keywords in ACC (token.c) and compile to a fixed
# sequence of p-codes (parse.c, LeadingPrint/LeadingHudMessage/...).
ACC_STATEMENTS = [
    ("print", "Print", ["PCD_BEGINPRINT", "PCD_ENDPRINT"]),
    ("printbold", "PrintBold", ["PCD_BEGINPRINT", "PCD_ENDPRINTBOLD"]),
    ("log", "Log", ["PCD_BEGINPRINT", "PCD_ENDLOG"]),
    (
        "hudmessage",
        "HudMessage",
        [
            "PCD_BEGINPRINT",
            "PCD_MOREHUDMESSAGE",
            "PCD_OPTHUDMESSAGE",
            "PCD_ENDHUDMESSAGE",
        ],
    ),
    (
        "hudmessagebold",
        "HudMessageBold",
        [
            "PCD_BEGINPRINT",
            "PCD_MOREHUDMESSAGE",
            "PCD_OPTHUDMESSAGE",
            "PCD_ENDHUDMESSAGEBOLD",
        ],
    ),
    ("strparam", "StrParam", ["PCD_BEGINPRINT", "PCD_SAVESTRING"]),
    (
        "createtranslation",
        "CreateTranslation",
        ["PCD_STARTTRANSLATION", "PCD_ENDTRANSLATION"],
    ),
]


def load_acc_builtins(path: Path) -> tuple[list[AccBuiltin], list[str]]:
    builtins, header = [], []
    for line in read_text(path).splitlines():
        if line.startswith("#"):
            header.append(line[1:].strip())
            continue
        if not line.strip() or line.startswith("name\t"):
            continue
        name, display, kind, lo, hi, returns, pcodes = line.split("\t")
        parsed = []
        for item in pcodes.split(","):
            pcd, num = item.split("=")
            parsed.append((pcd, int(num)))
        builtins.append(
            AccBuiltin(name, display, kind, int(lo), int(hi), returns == "yes", parsed)
        )
    return builtins, header


def vendor_acc_builtins(acc_src: Path, out: Path) -> None:
    """Re-extract ``acc_builtins.tsv`` from an rheit/acc checkout, keeping display names."""
    old_display = {}
    if out.exists():
        old_display = {b.name: b.display for b in load_acc_builtins(out)[0]}
    pcode_text = read_text(acc_src / "pcode.h")
    pcd_values = parse_c_enum(enum_body(pcode_text, "PCD_NOP,"))
    symbol_text = read_text(acc_src / "symbol.c")
    start = symbol_text.index("InternalFunctions[]")
    body = symbol_text[start : symbol_text.index("};", start)]
    rows = []
    for name, fields in re.findall(r'\{\s*"(\w+)"\s*,([^}]*)\}', body):
        direct, stack, argc, opt_mask, _out, returns, _latent = (
            f.strip() for f in fields.split(",")
        )
        optional = sum(bin(int(part, 0)).count("1") for part in opt_mask.split("|"))
        pcodes = [p for p in (direct, stack) if p != "PCD_NOP"]
        rows.append(
            (name, "builtin", int(argc) - optional, int(argc), returns == "YES", pcodes)
        )
    token_text = read_text(acc_src / "token.c")
    for name, _display, pcodes in ACC_STATEMENTS:
        if f'"{name}"' not in token_text:
            raise ValueError(f"Statement keyword {name!r} not found in token.c")
        rows.append((name, "statement", -1, -1, False, pcodes))
    version = re.search(
        r'#define\s+VERSION_TEXT\s+"([^"]+)"', read_text(acc_src / "acc.c")
    )
    lines = [
        "# ACC p-code built-ins and print-like statements (not declared in zspecial.acs).",
        f"# Extracted by {GENERATOR} --acc-src from rheit/acc"
        + (f" version {version.group(1)}" if version else "")
        + ": symbol.c InternalFunctions[], token.c keywords, pcode.h opcode numbers.",
        "# Upstream: https://github.com/rheit/acc/tree/1.60",
        "# 'display' is the conventional CamelCase spelling (ACS is case-insensitive).",
        "# args_min/args_max = -1 for statements with a free-form (printf-like) argument list.",
        "\t".join(TSV_COLUMNS),
    ]
    statement_display = {n: d for n, d, _ in ACC_STATEMENTS}
    for name, kind, lo, hi, returns, pcodes in rows:
        display = old_display.get(name) or statement_display.get(name, name)
        pcode_field = ",".join(f"{p}={pcd_values[p]}" for p in pcodes)
        lines.append(
            "\t".join(
                [
                    name,
                    display,
                    kind,
                    str(lo),
                    str(hi),
                    "yes" if returns else "no",
                    pcode_field,
                ]
            )
        )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({len(rows)} rows)")


def acc_version(acc_dir: Path) -> str:
    for candidate in (acc_dir / "acc", acc_dir / "acc.exe"):
        if candidate.is_file():
            match = re.search(
                rb"This is version ([0-9.]+) \(([^)]*)\)", candidate.read_bytes()
            )
            if match:
                return f"ACC {match.group(1).decode()} ({match.group(2).decode()})"
    return "ACC (version unknown: no acc binary next to zspecial.acs)"


