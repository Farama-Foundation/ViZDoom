@dataclass
class Actor:
    name: str
    parent: str
    replaces: str
    native: bool
    path: str
    game: str


ACTOR_RE = re.compile(
    r"^\s*actor\s+([\w.]+)(?:\s*:\s*([\w.]+))?(?:\s+replaces\s+([\w.]+))?(?:\s+-?\d+)?(\s+native)?\b",
    re.I | re.M,
)


def decorate_files(static: Path) -> list[str]:
    seen: list[str] = []

    def visit(rel: str) -> None:
        if rel.lower() in (s.lower() for s in seen):
            return
        seen.append(rel)
        for inc in re.findall(
            r'^\s*#include\s+"([^"]+)"', read_text(static / rel), flags=re.M | re.I
        ):
            visit(inc)

    visit("decorate.txt")
    return seen


def parse_actors(static: Path) -> list[Actor]:
    actors = []
    for rel in decorate_files(static):
        parts = Path(rel).parts
        game = parts[1] if len(parts) > 2 and parts[0] == "actors" else "base"
        text = strip_c_comments(read_text(static / rel))
        for name, parent, replaces, native in ACTOR_RE.findall(text):
            actors.append(
                Actor(name, parent or "", replaces or "", bool(native), rel, game)
            )
    return actors


def parse_mapinfo_numbers(
    static: Path, root_rel: str
) -> tuple[dict[int, str], dict[int, str]]:
    """Follow MAPINFO includes; return DoomEdNums and SpawnNums (later entries win)."""
    ednums: dict[int, str] = {}
    spawnnums: dict[int, str] = {}

    def visit(rel: str) -> None:
        text = strip_c_comments(read_text(static / rel))
        for inc in re.findall(r'^\s*include\s+"([^"]+)"', text, flags=re.M | re.I):
            visit(inc)
        for block, body in re.findall(
            r"^\s*(doomednums|spawnnums)\s*\{(.*?)\}", text, flags=re.M | re.S | re.I
        ):
            target = ednums if block.lower() == "doomednums" else spawnnums
            for num, value in re.findall(
                r"^\s*(\d+)\s*=\s*(\"[^\"]*\"|[\w.]+)", body, flags=re.M
            ):
                target[int(num)] = value.strip('"')

    visit(root_rel)
    return ednums, spawnnums


